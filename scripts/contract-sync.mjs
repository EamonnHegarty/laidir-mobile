// Downloads the pinned laidir-api contract into contract/ and generates src/generated/openapi.ts.
// Usage: pnpm contract:sync. CI runs it and fails if the committed files differ.
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import openapiTS, { astToString } from "openapi-typescript";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const { repo, ref, files } = JSON.parse(await readFile(join(root, "contract.json"), "utf8"));

if (!/^[0-9a-f]{40}$/.test(ref)) {
  throw new Error(`contract.json ref must be a full commit SHA, got "${ref}"`);
}

const contractDir = join(root, "contract");
await rm(contractDir, { recursive: true, force: true });

for (const path of files) {
  const url = `https://raw.githubusercontent.com/${repo}/${ref}/${path}`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`GET ${url}: ${res.status} ${res.statusText}`);
  const body = await res.text();
  JSON.parse(body); // every contract file is JSON; fail early on anything else
  const out = join(contractDir, path);
  await mkdir(dirname(out), { recursive: true });
  await writeFile(out, body);
  console.log(`contract/${path}`);
}

const spec = JSON.parse(await readFile(join(contractDir, "openapi/openapi.bundled.json"), "utf8"));
const ast = await openapiTS(spec);
const header = `// Generated by scripts/contract-sync.mjs from ${repo}@${ref}. Do not edit.\n\n`;
const generated = join(root, "src/generated/openapi.ts");
await mkdir(dirname(generated), { recursive: true });
await writeFile(generated, header + astToString(ast));
console.log("src/generated/openapi.ts");
