import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";

import contract from "../../contract.json";

const root = join(__dirname, "../..");

describe("pinned contract", () => {
  it("has every listed file synced", () => {
    for (const file of contract.files) expect(existsSync(join(root, "contract", file))).toBe(true);
  });

  it("generated types come from the pinned ref", () => {
    const generated = readFileSync(join(root, "src/generated/openapi.ts"), "utf8");
    expect(generated).toMatch(
      new RegExp(
        `^// Generated by scripts/contract-sync\\.mjs from ${contract.repo}@${contract.ref}\\.`,
      ),
    );
  });
});
